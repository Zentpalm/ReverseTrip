export type MessageKey = keyof typeof messages;
export function translate(locale: Locale, key: MessageKey) {
  return messages[key][locale === 'th' ? 0 : 1];
}
export function errorMessage(locale: Locale, key: string) {
  return key in messages ? translate(locale, key as MessageKey) : translate(locale, 'server_error');
}
export function localized<T extends { title_th: string; title_en: string }>(a: T, locale: Locale) {
  return locale === 'th' ? a.title_th : a.title_en;
}
export function dateLabel(value: string, locale: Locale, withTime = false) {
  return new Intl.DateTimeFormat(locale === 'th' ? 'th-TH-u-ca-gregory' : 'en-GB', {
    timeZone: 'Asia/Bangkok',
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    ...(withTime ? { hour: '2-digit', minute: '2-digit' } : {}),
  }).format(new Date(value.length === 10 ? value + 'T12:00:00+07:00' : value));
}
export function timeLabel(value: string) {
  return new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Asia/Bangkok',
    hour: '2-digit',
    minute: '2-digit',
  }).format(new Date(value));
}
